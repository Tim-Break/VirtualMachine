public enum CMD : byte
{
    mov_r = 0x02,
    mov_i = 0x01,

    load = 0x04,
    store = 0x05,

    add_r = 0x10,
    sub_r = 0x11,
    mul_r = 0x12,
    div_r = 0x13,

    shl_r = 0x14,
    shr_r = 0x15,

    and_r = 0x16,
    or_r = 0x17,
    xor_r = 0x18,

    cmp_r = 0x19,

    add_i = 0x1A,
    sub_i = 0x1B,
    mul_i = 0x1C,
    div_i = 0x1D,

    shl_i = 0x1E,
    shr_i = 0x1F,

    and_i = 0x20,
    or_i = 0x21,
    xor_i = 0x22,

    cmp_i = 0x23,

    not = 0x24,

    push = 0x2D,
    pop = 0x2E,

    jmp_r = 0x30,
    jz_r = 0x31,
    jnz_r = 0x32,

    jmp_a = 0x37,
    jz_a = 0x38,
    jnz_a = 0x39,

    call = 0x34,
    ret = 0x35,

    lea = 0x40,

    int_ = 0x50,
    iret = 0x51,

    in_ = 0x60,
    out_ = 0x61,

    halt = 0xFF
}